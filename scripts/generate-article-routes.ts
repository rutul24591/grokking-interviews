#!/usr/bin/env node

/**
 * Generate Article Routes Manifest
 * 
 * Scans content/articles/ and generates lib/article-routes.ts
 * 
 * Usage: pnpm tsx scripts/generate-article-routes.ts
 */

import * as fs from "fs";
import * as path from "path";

const ARTICLES_DIR = path.join(process.cwd(), "content", "articles");
const ARTICLE_ROUTES_DIR = path.join(process.cwd(), "lib", "article-routes");
const OUTPUT_FILE = path.join(process.cwd(), "lib", "article-routes.ts");

// Map filesystem paths to sidebar slugs
const PATH_MAPPINGS: Record<string, string> = {
  "system-design/frontend": "system-design-concepts/frontend-concepts",
  "system-design/backend": "system-design-concepts/backend-concepts",
  "requirements/functional-requirements": "requirements/functional-requirements",
  "requirements/non-functional-requirements": "requirements/non-functional-requirements",
  "system-design-problems/high-level-design": "system-design-problems/high-level-design",
  "system-design-problems/low-level-design": "system-design-problems/low-level-design",
  "other/artificial-intelligence": "other/artificial-intelligence",
  "other/data-structures-algorithms": "other/data-structures-algorithms",
  "other/leetcode": "other/leetcode",
  "other/ci-cd": "other/ci-cd",
};

function main() {
  console.log("🔍 Scanning article files...\n");

  const routesByDomain: Record<string, string[]> = {
    "system-design-concepts": [],
    "requirements": [],
    "system-design-problems": [],
    "other": [],
  };
  const subcategoryArticles: Map<string, Array<{slug: string, title: string, description: string}>> = new Map();
  let count = 0;

  // Walk through all article directories
  for (const [fsPath, sidebarPath] of Object.entries(PATH_MAPPINGS)) {
    const fullDir = path.join(ARTICLES_DIR, fsPath);

    if (!fs.existsSync(fullDir)) {
      console.warn(`⚠️  Directory not found: ${fullDir}`);
      continue;
    }

    // Recursively find all .tsx files
    const files = findAllTsxFiles(fullDir);

    for (const file of files) {
      const content = fs.readFileSync(file, "utf-8");
      const trimmed = content.trim();
      if (!trimmed) {
        console.warn(
          `⚠️  Skipping empty article file: ${path.relative(process.cwd(), file)}`,
        );
        continue;
      }
      if (!/\bexport\s+default\b/.test(trimmed)) {
        console.warn(
          `⚠️  Skipping non-module article file (missing 'export default'): ${path.relative(
            process.cwd(),
            file,
          )}`,
        );
        continue;
      }

      const relativePath = path.relative(fullDir, file).replace(/\.tsx$/, '');
      const parts = relativePath.split(path.sep);

      // Build sidebar key: category/subcategory/topic
      const sidebarKey = `${sidebarPath}/${parts.join("/")}`;

      // Build import path
      const importPath = `@/content/articles/${fsPath}/${relativePath}`;

      // Generate route entry — bucket by domain
      const domain = sidebarPath.split("/")[0];
      if (domain in routesByDomain) {
        routesByDomain[domain].push(`  "${sidebarKey}": () => import("${importPath}"),`);
      }
      count++;

      // Extract metadata for subcategory manifest
      const titleMatch = content.match(/title:\s*"([^"]*)"/);
      const descMatch = content.match(/description:\s*"([^"]*)"/);

      // Build subcategory key using sidebar path format: domain/category/subcategory
      // parts[0] = subcategory, parts[1] = topic
      // sidebarPath already includes domain/category (e.g., "system-design-concepts/frontend-concepts")
      const subcategoryKey = `${sidebarPath}/${parts[0]}`;
      if (!subcategoryArticles.has(subcategoryKey)) {
        subcategoryArticles.set(subcategoryKey, []);
      }
      subcategoryArticles.get(subcategoryKey)!.push({
        slug: parts[parts.length - 1],
        title: titleMatch ? titleMatch[1] : parts[parts.length - 1],
        description: descMatch ? descMatch[1] : '',
      });
    }
  }

  // Generate split article-routes files
  if (!fs.existsSync(ARTICLE_ROUTES_DIR)) {
    fs.mkdirSync(ARTICLE_ROUTES_DIR, { recursive: true });
  }

  const domainExportNamesRoutes: Record<string, string> = {
    "system-design-concepts": "systemDesignConceptsRoutes",
    "requirements": "requirementsRoutes",
    "system-design-problems": "systemDesignProblemsRoutes",
    "other": "otherRoutes",
  };

  const domainFileNamesRoutes: Record<string, string> = {
    "system-design-concepts": "system-design-concepts",
    "requirements": "requirements",
    "system-design-problems": "system-design-problems",
    "other": "other",
  };

  for (const [domain, routeLines] of Object.entries(routesByDomain)) {
    const exportName = domainExportNamesRoutes[domain];
    const fileName = domainFileNamesRoutes[domain];
    const domainContent = `/**
 * Article Routes — ${domain}
 *
 * AUTO-GENERATED by scripts/generate-article-routes.ts
 * DO NOT EDIT MANUALLY
 *
 * To update: run \`pnpm generate-article-routes\`
 */

import type { ArticleModule } from "./types";

export const ${exportName}: Record<string, () => Promise<ArticleModule>> = {
${routeLines.join("\n")}
};
`;
    fs.writeFileSync(path.join(ARTICLE_ROUTES_DIR, `${fileName}.ts`), domainContent, "utf-8");
  }

  // Write the index barrel for article-routes
  const articleRoutesTypes = `import type { ComponentType } from "react";
import type { ArticleMetadata } from "@/types/article";

export type ArticleModule = {
  metadata?: ArticleMetadata;
  default?: ComponentType;
};
`;
  fs.writeFileSync(path.join(ARTICLE_ROUTES_DIR, "types.ts"), articleRoutesTypes, "utf-8");

  const articleRoutesIndex = `import { systemDesignConceptsRoutes } from "./system-design-concepts";
import { requirementsRoutes } from "./requirements";
import { systemDesignProblemsRoutes } from "./system-design-problems";
import { otherRoutes } from "./other";
import type { ArticleModule } from "./types";

export const articleRoutes: Record<string, () => Promise<ArticleModule>> = {
  ...systemDesignConceptsRoutes,
  ...requirementsRoutes,
  ...systemDesignProblemsRoutes,
  ...otherRoutes,
};

/**
 * Get all article paths for static generation
 */
export function getAllArticlePaths() {
  return Object.keys(articleRoutes).map((key) => {
    const parts = key.split("/");
    return {
      domain: parts[0],
      category: parts[1],
      subcategory: parts[2],
      topic: parts[3],
    };
  });
}

/**
 * Load an article by its path
 */
export async function loadArticle(domain: string, category: string, subcategory: string, topic: string) {
  const key = \`\${domain}/\${category}/\${subcategory}/\${topic}\`;
  const loadModule = articleRoutes[key];

  if (!loadModule) {
    return null;
  }

  try {
    const articleModule = await loadModule();
    if (!articleModule.default) {
      return null;
    }

    return {
      metadata: articleModule.metadata,
      component: articleModule.default,
    };
  } catch {
    return null;
  }
}
`;
  fs.writeFileSync(path.join(ARTICLE_ROUTES_DIR, "index.ts"), articleRoutesIndex, "utf-8");

  // Generate split subcategory manifests by domain
  const domains: Record<string, Record<string, Array<{slug: string, title: string, description: string}>>> = {
    "system-design-concepts": {},
    "requirements": {},
    "system-design-problems": {},
    "other": {},
  };

  for (const [key, articles] of subcategoryArticles.entries()) {
    const domain = key.split("/")[0];
    if (domain in domains) {
      domains[domain][key] = articles;
    }
  }

  const SUBCATEGORY_DIR = path.join(process.cwd(), "lib", "subcategory-articles");
  if (!fs.existsSync(SUBCATEGORY_DIR)) {
    fs.mkdirSync(SUBCATEGORY_DIR, { recursive: true });
  }

  const domainExportNames: Record<string, string> = {
    "system-design-concepts": "systemDesignConceptsArticles",
    "requirements": "requirementsArticles",
    "system-design-problems": "systemDesignProblemsArticles",
    "other": "otherArticles",
  };

  const domainFileNames: Record<string, string> = {
    "system-design-concepts": "system-design-concepts",
    "requirements": "requirements",
    "system-design-problems": "system-design-problems",
    "other": "other",
  };

  for (const [domain, entries] of Object.entries(domains)) {
    const exportName = domainExportNames[domain];
    const fileName = domainFileNames[domain];
    const content = `/**
 * Subcategory Articles Manifest — ${domain}
 *
 * AUTO-GENERATED by scripts/generate-article-routes.ts
 * DO NOT EDIT MANUALLY
 *
 * To update: run \`pnpm generate-article-routes\`
 */

export const ${exportName}: Record<string, Array<{slug: string; title: string; description: string}>> = ${JSON.stringify(entries, null, 2)};
`;
    fs.writeFileSync(path.join(SUBCATEGORY_DIR, `${fileName}.ts`), content, "utf-8");
  }

  // Write the index barrel
  const indexContent = `import { systemDesignConceptsArticles } from "./system-design-concepts";
import { requirementsArticles } from "./requirements";
import { systemDesignProblemsArticles } from "./system-design-problems";
import { otherArticles } from "./other";

export const subcategoryArticles: Record<string, Array<{slug: string; title: string; description: string}>> = {
  ...systemDesignConceptsArticles,
  ...requirementsArticles,
  ...systemDesignProblemsArticles,
  ...otherArticles,
};
`;
  fs.writeFileSync(path.join(SUBCATEGORY_DIR, "index.ts"), indexContent, "utf-8");

  // Write the re-export barrel at the original location
  const SUBCATEGORY_OUTPUT_FILE = path.join(process.cwd(), "lib", "subcategory-articles.ts");
  fs.writeFileSync(SUBCATEGORY_OUTPUT_FILE, `export { subcategoryArticles } from "./subcategory-articles/index";\n`, "utf-8");

  // Write the re-export barrel at the original location
  fs.writeFileSync(OUTPUT_FILE, `export { articleRoutes, getAllArticlePaths, loadArticle } from "./article-routes/index";\n`, "utf-8");

  console.log("=".repeat(60));
  console.log("📊 SUMMARY");
  console.log("=".repeat(60));
  console.log(`Articles scanned:  ${count}`);
  console.log(`Output: ${path.relative(process.cwd(), OUTPUT_FILE)}`);
  console.log(`Size: ${(fs.statSync(OUTPUT_FILE).size / 1024).toFixed(2)} KB`);
  console.log("\n✅ Article routes manifest generated successfully!");
  console.log("\n📝 Next steps:");
  console.log("   - Run 'pnpm build' to rebuild the app");
  console.log("");
}

function findAllTsxFiles(dir: string): string[] {
  const files: string[] = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    
    if (entry.isDirectory()) {
      files.push(...findAllTsxFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith(".tsx")) {
      files.push(fullPath);
    }
  }

  return files;
}

main();
